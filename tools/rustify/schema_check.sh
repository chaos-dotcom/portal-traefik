#!/bin/sh
# Check the Rust image's schema files against Alembic (see apps/api-rs/migrations/README.md):
#   - apps/api-rs/schema.sql is exactly what Alembic produces at head, stamp included;
#   - applying apps/api-rs/migrations/*.sql to a database at the oldest revision they start from
#     reproduces that head schema;
#   - every migration file is registered in MIGRATIONS (apps/api-rs/src/migrate.rs).
#
#   tools/rustify/schema_check.sh            # check; exit 1 on drift
#   tools/rustify/schema_check.sh --write    # regenerate schema.sql from Alembic
#
# Runs Alembic (via uv) against a throwaway postgres:16 container on a random loopback port.
set -eu

root=$(cd "$(dirname "$0")/../.." && pwd)
schema="$root/apps/api-rs/schema.sql"
name="portal-schema-check-$$"

docker run -d --rm --name "$name" -p 127.0.0.1::5432 \
	-e POSTGRES_USER=portal -e POSTGRES_PASSWORD=portal -e POSTGRES_DB=portal postgres:16 >/dev/null
trap 'docker rm -f "$name" >/dev/null 2>&1 || true' EXIT
port=$(docker port "$name" 5432/tcp | head -1 | sed 's/.*://')
until docker exec "$name" pg_isready -U portal -d portal >/dev/null 2>&1; do sleep 0.5; done

# alembic_to <database> <revision>
alembic_to() {
	log=$(mktemp)
	if ! (
		cd "$root/apps/api"
		DATABASE_URL="postgresql+asyncpg://portal:portal@127.0.0.1:$port/$1" \
			SESSION_SECRET=schema-check TOKEN_ENCRYPTION_KEY=schema-check \
			uv run --quiet --frozen alembic upgrade "$2"
	) >"$log" 2>&1; then
		cat "$log" >&2
		echo "alembic upgrade $2 failed" >&2
		rm -f "$log"
		exit 1
	fi
	rm -f "$log"
}
alembic_to portal head
head=$(docker exec "$name" psql -U portal -d portal -tAc "SELECT version_num FROM alembic_version" | tr -d '[:space:]')

generated=$(mktemp)
trap 'rm -f "$generated" "$generated.want" "$generated.got" "$generated.chain" "$generated.head"; docker rm -f "$name" >/dev/null 2>&1 || true' EXIT
{
	docker exec "$name" pg_dump -U portal -d portal --schema-only --no-owner --no-privileges
	cat <<EOF

--
-- Alembic revision this schema corresponds to. A database created from this file is stamped with
-- it, so Alembic (and the Python reference API) see a normal, up-to-date database. portal-api
-- migrate upgrades older revisions with migrations/ and refuses unknown ones (src/migrate.rs).
-- Generated by tools/rustify/schema_check.sh --write; CI fails if it drifts from Alembic.
--
INSERT INTO public.alembic_version (version_num) VALUES ('$head');
EOF
} >"$generated"

# Ignore what varies between dumps of the same schema: the \restrict/\unrestrict lines carrying a
# random key, and the server/pg_dump version banner.
if [ "${1:-}" = "--write" ]; then
	cp "$generated" "$schema"
	echo "wrote $schema (revision $head)"
	exit 0
fi
stable() { grep -v -e '^\\\(un\)\?restrict ' -e '^-- Dumped \(from database\|by pg_dump\) version ' "$1"; }
stable "$schema" >"$generated.want"
stable "$generated" >"$generated.got"
if diff -u "$generated.want" "$generated.got"; then
	echo "schema.sql matches Alembic head ($head)"
else
	echo "schema.sql has drifted from Alembic head ($head) — run: $0 --write" >&2
	exit 1
fi

# --- migrations: each file starts with "-- portal-migration: <from> -> <to>" -------------------
migrations="$root/apps/api-rs/migrations"
steps=$(for f in "$migrations"/*.sql; do
	[ -e "$f" ] || continue
	sed -n '1s/^-- portal-migration: \([0-9a-f]*\) -> \([0-9a-f]*\)$/\1 \2/p' "$f" | grep . ||
		{ echo "$f: first line must be '-- portal-migration: <from> -> <to>'" >&2; echo BAD; }
done)
case "$steps" in *BAD*) exit 1 ;; esac
if [ -z "$steps" ]; then
	echo "no migrations to check (schema.sql is the only revision this image knows)"
	exit 0
fi
for to in $(printf '%s\n' "$steps" | cut -d' ' -f2); do
	grep -v '^[[:space:]]*//' "$root/apps/api-rs/src/migrate.rs" | grep -qF "include_str!(\"../migrations/$to.sql\")" ||
		{ echo "migrations/$to.sql is not registered in MIGRATIONS (src/migrate.rs)" >&2; exit 1; }
done
# The oldest revision is the one no step leads to; walk the chain from there to the head.
oldest=$(printf '%s\n' "$steps" | while read -r from _; do printf '%s\n' "$steps" | cut -d' ' -f2 | grep -qx "$from" || echo "$from"; done)
[ "$(printf '%s\n' "$oldest" | wc -l)" -eq 1 ] || { echo "migrations don't form one chain (starts: $oldest)" >&2; exit 1; }
docker exec "$name" createdb -U portal chain
alembic_to chain "$oldest"
at=$oldest
while [ "$at" != "$head" ]; do
	to=$(printf '%s\n' "$steps" | awk -v f="$at" '$1 == f { print $2 }')
	[ -n "$to" ] || { echo "no migration from $at towards $head" >&2; exit 1; }
	grep -v '^\\' "$migrations/$to.sql" | docker exec -i "$name" psql -q -U portal -d chain -v ON_ERROR_STOP=1 >/dev/null
	at=$to
done
docker exec "$name" pg_dump -U portal -d chain --schema-only --no-owner --no-privileges | stable /dev/stdin >"$generated.chain"
docker exec "$name" pg_dump -U portal -d portal --schema-only --no-owner --no-privileges | stable /dev/stdin >"$generated.head"
if diff -u "$generated.head" "$generated.chain"; then
	echo "migrations $oldest -> $head reproduce the head schema"
else
	echo "applying migrations/ from $oldest does not reproduce Alembic head ($head)" >&2
	exit 1
fi
